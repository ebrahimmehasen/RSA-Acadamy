assert.equal((logger.match(/\.delete\(\)\s*\.eq\('event_type', DIAGNOSTIC_EVENT\)/g)||[]).length,2);
assert.match(readFileSync('supabase/migrations/0010_security.sql','utf8'),/using \(public.is_admin\(\)\)/);
